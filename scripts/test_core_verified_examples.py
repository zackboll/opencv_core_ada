"""Fail-closed platform selection and installed-wheel compiler-input controls."""
import copy
import json
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from core_verified_examples import (MAPPINGS, CONFIGURATION, selected_mapping,
                                    compiler_destinations, digest)

ROOT = Path(__file__).resolve().parent.parent


class VerifiedExamples(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / 'input'
        shutil.copytree(ROOT / 'obj/docs/enhancer-input', self.root)

    def test_actual_configuration_selects_exact_reviewed_map(self):
        setting, data = selected_mapping(self.root)
        self.assertIn(setting, MAPPINGS.values())
        self.assertEqual(len(data['inputs']), 27)
        self.assertEqual(len(data['mappings']), 4)
        self.assertEqual(len(data['skipped']), 1)

    def test_both_generated_configurations_select_only_their_map(self):
        # Exact generated bytes from the two qualifications, not an OS selector.
        path = self.root / CONFIGURATION
        original = path.read_bytes()
        for distro, other in ((b'debian', b'ubuntu'), (b'ubuntu', b'debian')):
            if b'"' + distro + b'"' not in original:
                continue
            variant = original.replace(b'Alire_Host_Distro := "' + distro + b'";',
                                       b'Alire_Host_Distro := "' + other + b'";')
            self.assertIn(digest(variant), MAPPINGS)
            # Both complete maps are immutable project files; copy the other
            # into the disposable verification snapshot before switching bytes.
            name, pin = MAPPINGS[digest(variant)]
            shutil.copyfile(ROOT / name, self.root / name)
            path.write_bytes(variant)
            self.assertEqual(selected_mapping(self.root)[0], (name, pin))
            path.write_bytes(original)

    def test_mapping_symlink_substitution(self):
        (name, _), _ = selected_mapping(self.root)
        path = self.root / name
        payload = path.read_bytes()
        outside = Path(self.temp.name) / 'mapping.json'
        outside.write_bytes(payload)
        path.unlink()
        path.symlink_to(outside)
        with self.assertRaises(ValueError):
            selected_mapping(self.root)

    def test_unknown_configuration_fails_closed(self):
        path = self.root / CONFIGURATION
        path.write_bytes(path.read_bytes() + b'\n')
        with self.assertRaisesRegex(ValueError, 'unqualified compiler configuration'):
            selected_mapping(self.root)

    def test_wrong_mapping_substitution(self):
        (name, _), data = selected_mapping(self.root)
        data['inputs'][CONFIGURATION] = '0' * 64
        (self.root / name).write_text(json.dumps(data))
        with self.assertRaisesRegex(ValueError, 'unreviewed compiler mapping'):
            selected_mapping(self.root)

    def test_stale_source_hash(self):
        path = self.root / 'src/opencv-core.ads'
        path.write_bytes(path.read_bytes() + b'\n')
        with self.assertRaisesRegex(ValueError, 'stale/missing compiler input'):
            selected_mapping(self.root)

    def test_missing_internal_compiler_input(self):
        (self.root / 'src/internal/opencv-internal-c_api.ads').unlink()
        with self.assertRaises((ValueError, OSError)):
            selected_mapping(self.root)

    def test_stale_project(self):
        path = self.root / 'docs/example.gpr'
        path.write_bytes(path.read_bytes() + b'\n')
        with self.assertRaises(ValueError):
            selected_mapping(self.root)

    def test_public_and_compiler_inventories_are_separate(self):
        public = list((self.root / 'public').rglob('*.ads'))
        self.assertEqual(len(public), 195)
        self.assertFalse(any('internal' in p.parts for p in public))
        self.assertEqual(len(list((self.root / 'src/internal').glob('*.ads'))), 2)
        self.assertFalse(any(p.is_symlink() for p in self.root.rglob('*')))

    def installed_rejection(self, mutate):
        """Even a re-pinned forged mapping must fail the released consumer."""
        (name, pin), data = selected_mapping(self.root)
        mutate(data)
        payload = (json.dumps(data, sort_keys=True, indent=2) + '\n').encode()
        (self.root / name).write_bytes(payload)
        config = self.root / 'docs/gnatdoc-enhancer.toml'
        config.write_text(config.read_text().replace(pin, digest(payload)))
        site = Path(self.temp.name) / 'site'
        shutil.copytree(ROOT / 'obj/docs/native', site)
        result = subprocess.run([str(ROOT / '.doc-tools/enhancer/bin/gnatdoc-enhancer'),
            'enhance', '--dry-run', '--source-root', str(self.root), '--config', 'docs/gnatdoc-enhancer.toml',
            '--site', str(site)], text=True, capture_output=True)
        self.assertNotEqual(result.returncode, 0, result.stdout)

    def test_rehashed_call_coordinate_rejected_by_wheel(self):
        self.installed_rejection(lambda d: d['mappings'][1]['occurrence'].update(column=33))

    def test_rehashed_incomplete_compiler_inputs_rejected_by_wheel(self):
        self.installed_rejection(lambda d: d['inputs'].pop('docs/example.gpr'))

    def test_rehashed_stale_mapping_rejected_by_wheel(self):
        self.installed_rejection(lambda d: d['inputs'].update({'docs/example.gpr': '0' * 64}))

    def test_rehashed_complete_wrong_overload_rejected_by_independent_oracle(self):
        _, mapping = selected_mapping(ROOT)
        forged = copy.deepcopy(mapping)
        clone = forged['mappings'][1]
        clone['profile'] = 'function Clone (Self : UMat) return UMat;'
        # Matching self-consistent forged metadata is not compiler authority.
        with patch('core_verified_examples.selected_mapping', return_value=(None, forged)):
            with self.assertRaisesRegex(ValueError, 'complete compiler profile'):
                compiler_destinations(ROOT, ROOT / 'obj/docs/native')

    def test_rehashed_coordinate_rejected_by_independent_oracle(self):
        _, mapping = selected_mapping(ROOT)
        forged = copy.deepcopy(mapping)
        forged['mappings'][1]['occurrence']['start'] += 1
        with patch('core_verified_examples.selected_mapping', return_value=(None, forged)):
            with self.assertRaisesRegex(ValueError, 'call coordinates'):
                compiler_destinations(ROOT, ROOT / 'obj/docs/native')

    def test_rehashed_mat_umat_identity_disagreement_rejected_by_wheel(self):
        self.installed_rejection(lambda d: d['mappings'][1]['selected'].update(line=4914))

    def test_immutable_mappings_semantically_equal(self):
        a, b = [json.loads((ROOT / name).read_bytes()) for name, _ in MAPPINGS.values()]
        self.assertEqual(a['native_sha256'], b['native_sha256'])
        self.assertEqual(a['provenance']['ali'], b['provenance']['ali'])
        for left, right in zip(a['mappings'], b['mappings']):
            for key in ('selected', 'compiler_selected', 'profile', 'occurrence', 'identity', 'source'):
                self.assertEqual(left[key], right[key])


if __name__ == '__main__':
    unittest.main()