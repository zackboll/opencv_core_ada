#!/bin/sh

set -eu

output=config/opencv_core_install.gpr

if ! command -v pkg-config >/dev/null 2>&1; then
    echo "error: pkg-config is required to locate OpenCV Core" >&2
    exit 1
fi

package=
for candidate in opencv5 opencv4 opencv
do
    if pkg-config --exists "$candidate"; then
        package=$candidate
        break
    fi
done

if [ -z "$package" ]; then
    echo "error: pkg-config package was not found (tried opencv5, opencv4, opencv)" >&2
    exit 1
fi

include_dir=$(pkg-config --variable=includedir "$package")

if [ -z "$include_dir" ]; then
    include_dir=$(pkg-config --variable=includedir_new "$package")
fi

library_dir=$(pkg-config --variable=libdir "$package")

if [ -z "$include_dir" ] || [ -z "$library_dir" ]; then
    echo "error: '$package' does not define a usable include directory and libdir" >&2
    exit 1
fi

# Homebrew OpenCV on macOS is built with Apple clang++ and libc++. The C++
# shim must use that same compiler and runtime. Linux OpenCV uses g++ and
# libstdc++, which remains the default.
cxx_runtime_switch="-lstdc++"
cxx_driver="g++"
use_apple_clang="False"
sysname=$(uname -s)

if [ "$sysname" = "Darwin" ]; then
    use_apple_clang="True"
    cxx_runtime_switch="-lc++"
    if command -v xcrun >/dev/null 2>&1; then
        cxx_driver=$(xcrun --find clang++)
    elif command -v clang++ >/dev/null 2>&1; then
        cxx_driver=$(command -v clang++)
    else
        echo "error: Apple clang++ is required to compile the OpenCV C++ shim on macOS" >&2
        exit 1
    fi
fi

case "$include_dir$library_dir$cxx_driver" in
    *\"*)
        echo "error: OpenCV paths containing double quotes are unsupported" >&2
        exit 1
        ;;
esac

mkdir -p config

cat >"$output" <<EOF
--  Generated by scripts/configure_opencv.sh; do not edit.
abstract project OpenCV_Core_Install is
   type Apple_Clang_Kind is ("True", "False");
   Use_Apple_Clang : Apple_Clang_Kind := "${use_apple_clang}";
   Include_Switch := "-I${include_dir}";
   Library_Search_Switch := "-L${library_dir}";
   Cxx_Runtime_Switch := "${cxx_runtime_switch}";
   Cxx_Driver := "${cxx_driver}";
end OpenCV_Core_Install;
EOF
